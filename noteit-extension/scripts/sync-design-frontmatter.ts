// Copies the YAML frontmatter of the UX DESIGN.md into the tracked tree (Story 3.1).
// _bmad-output/ is gitignored, so the token drift test reads this committed copy instead.
// Usage: node scripts/sync-design-frontmatter.ts [--check]
//   (no flag) rewrite src/ui/tokens/design-frontmatter.md from DESIGN.md
//   --check   exit 1 when the committed copy differs from DESIGN.md (skipped when DESIGN.md is absent)
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const DESIGN_MD = resolve(
  root,
  '../_bmad-output/project-planning-artifacts/ux-designs/ux-noteit-2026-10-18/DESIGN.md',
)
export const FRONTMATTER_COPY = resolve(root, 'src/ui/tokens/design-frontmatter.md')

const HEADER =
  '<!-- Generated by scripts/sync-design-frontmatter.ts from the UX DESIGN.md. Do not edit. -->\n'

/** Frontmatter block (including both --- fences) of a DESIGN.md document, plus the header. */
export function extractFrontmatter(markdown: string): string {
  const match = /^---\n[\s\S]*?\n---\n/.exec(markdown)
  if (!match) throw new Error('DESIGN.md: frontmatter not found')
  return match[0] + '\n' + HEADER
}

function main(): void {
  const check = process.argv.includes('--check')
  if (!existsSync(DESIGN_MD)) {
    if (check) {
      console.log('sync-design-frontmatter: DESIGN.md not present, check skipped')
      return
    }
    console.error(`sync-design-frontmatter: ${DESIGN_MD} not found`)
    process.exit(1)
  }
  const expected = extractFrontmatter(readFileSync(DESIGN_MD, 'utf8'))
  if (check) {
    const actual = existsSync(FRONTMATTER_COPY) ? readFileSync(FRONTMATTER_COPY, 'utf8') : ''
    if (actual !== expected) {
      console.error('sync-design-frontmatter: copy is stale, run node scripts/sync-design-frontmatter.ts')
      process.exit(1)
    }
    console.log('sync-design-frontmatter: copy is up to date')
    return
  }
  writeFileSync(FRONTMATTER_COPY, expected)
  console.log(`sync-design-frontmatter: wrote ${FRONTMATTER_COPY}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
