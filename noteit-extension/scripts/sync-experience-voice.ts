// Copies the "Do" column of the EXPERIENCE.md Voice and Tone table into the tracked tree (Story 3.2).
// _bmad-output/ is gitignored, so the strings coverage test reads this committed copy instead.
// Usage: node scripts/sync-experience-voice.ts [--check]
//   (no flag) rewrite src/ui/voice-do.md from EXPERIENCE.md
//   --check   exit 1 when the committed copy differs from EXPERIENCE.md (skipped when it is absent)
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const EXPERIENCE_MD = resolve(
  root,
  '../_bmad-output/project-planning-artifacts/ux-designs/ux-noteit-2026-10-18/EXPERIENCE.md',
)
export const VOICE_COPY = resolve(root, 'src/ui/voice-do.md')

const HEADER =
  '<!-- Generated by scripts/sync-experience-voice.ts from the UX EXPERIENCE.md Voice and Tone table. Do not edit. -->\n'

/** "Do" cells of the Voice and Tone table, in table order. */
export function extractVoiceDo(markdown: string): string[] {
  const section = /^## Voice and Tone\n([\s\S]*?)(?=^## )/m.exec(markdown)
  if (!section) throw new Error('EXPERIENCE.md: Voice and Tone section not found')
  const rows = section[1].split('\n').filter((line) => line.startsWith('|'))
  // Skip the header row and the |---|---| separator.
  const cells = rows.slice(2).map((row) => row.split('|')[1]?.trim() ?? '')
  if (cells.length === 0) throw new Error('EXPERIENCE.md: Voice and Tone table is empty')
  return cells.filter((cell) => cell.length > 0)
}

export function renderVoiceCopy(cells: string[]): string {
  return HEADER + cells.map((cell) => `- ${cell}\n`).join('')
}

/** Parses the committed copy back into its list of "Do" entries. */
export function parseVoiceCopy(text: string): string[] {
  return text
    .split('\n')
    .filter((line) => line.startsWith('- '))
    .map((line) => line.slice(2))
}

function main(): void {
  const check = process.argv.includes('--check')
  if (!existsSync(EXPERIENCE_MD)) {
    if (check) {
      console.log('sync-experience-voice: EXPERIENCE.md not present, check skipped')
      return
    }
    console.error(`sync-experience-voice: ${EXPERIENCE_MD} not found`)
    process.exit(1)
  }
  const expected = renderVoiceCopy(extractVoiceDo(readFileSync(EXPERIENCE_MD, 'utf8')))
  if (check) {
    const actual = existsSync(VOICE_COPY) ? readFileSync(VOICE_COPY, 'utf8') : ''
    if (actual !== expected) {
      console.error('sync-experience-voice: copy is stale, run node scripts/sync-experience-voice.ts')
      process.exit(1)
    }
    console.log('sync-experience-voice: copy is up to date')
    return
  }
  writeFileSync(VOICE_COPY, expected)
  console.log(`sync-experience-voice: wrote ${VOICE_COPY}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
