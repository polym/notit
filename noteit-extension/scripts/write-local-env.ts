// Writes .env.local with the local Supabase stack's public API URL and anon key, so the next
// `npm run build` targets the local stack (E2E / CI only). Values come from `supabase status -o env`;
// nothing is hard-coded. .env.local is git-ignored (*.local) and must not be used for release builds.
// A developer's own .env.local (one this script did not generate) is never overwritten unless
// --force is passed, so `npm run verify` cannot silently replace a hand-written dev config.
// Usage: node scripts/write-local-env.ts [--force]
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const EXT_ROOT = resolve(import.meta.dirname, '..')
const REPO_ROOT = resolve(EXT_ROOT, '..')
export const LOCAL_ENV_PATH = resolve(EXT_ROOT, '.env.local')

/** First line of every generated file; marks a .env.local as safe to regenerate. */
export const GENERATED_HEADER = '# Generated by scripts/write-local-env.ts for the local Supabase stack. Do not commit.'

export type WriteDecision = 'write' | 'unchanged' | 'refuse'

/**
 * Whether to write `next` over the current .env.local contents (null when the file is absent).
 * Only an absent file, a file this script generated, or --force allows a write.
 */
export function writeDecision(current: string | null, next: string, force: boolean): WriteDecision {
  if (current === next) return 'unchanged'
  if (current === null || force) return 'write'
  return current.startsWith(GENERATED_HEADER) ? 'write' : 'refuse'
}

/** Parses `KEY="value"` lines from `supabase status -o env`. */
export function parseStatusEnv(output: string): Record<string, string> {
  const vars: Record<string, string> = {}
  for (const line of output.split('\n')) {
    const match = /^([A-Z0-9_]+)="?(.*?)"?$/.exec(line.trim())
    if (match) vars[match[1]] = match[2]
  }
  return vars
}

/** .env.local contents for the given status output; throws when API_URL or ANON_KEY is missing. */
export function localEnvFile(statusOutput: string): string {
  const vars = parseStatusEnv(statusOutput)
  if (!vars.API_URL || !vars.ANON_KEY) {
    throw new Error('`supabase status -o env` did not report API_URL and ANON_KEY.')
  }
  return [
    GENERATED_HEADER,
    `VITE_SUPABASE_URL=${vars.API_URL}`,
    `VITE_SUPABASE_ANON_KEY=${vars.ANON_KEY}`,
    '',
  ].join('\n')
}

function main(argv: string[]): number {
  const bin = resolve(EXT_ROOT, 'node_modules/.bin/supabase')
  let output: string
  try {
    output = execFileSync(bin, ['status', '-o', 'env', '--workdir', REPO_ROOT], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    })
  } catch {
    console.error('Local Supabase is not running. Run `npm run db:start` first.')
    return 1
  }
  const next = localEnvFile(output)
  const current = existsSync(LOCAL_ENV_PATH) ? readFileSync(LOCAL_ENV_PATH, 'utf8') : null
  const decision = writeDecision(current, next, argv.includes('--force'))
  if (decision === 'unchanged') {
    console.log(`[env:local] ${LOCAL_ENV_PATH} already targets the local stack`)
    return 0
  }
  if (decision === 'refuse') {
    console.error(
      `[env:local] ${LOCAL_ENV_PATH} exists and was not generated by this script; refusing to overwrite it.\n` +
        'Move it aside (it is your own dev config) or rerun with `npm run env:local -- --force`.',
    )
    return 1
  }
  writeFileSync(LOCAL_ENV_PATH, next)
  console.log(`[env:local] wrote ${LOCAL_ENV_PATH}`)
  return 0
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)))
}
